/**
 * lift-files-only (m4-gate G3, design §3.5): the record of the human's lift
 * decisions — `docs/guard/lifts.jsonl`, in every checkout of the project —
 * is written by the harness only. The rule judges the exact relative path,
 * not a directory, so a project's own docs/guard/ documents pass (review
 * N2); it judges every checkout of the session's project, so a worker's
 * committed copy in a work tree is covered too (review F14): a file tool's
 * target resolves to the checkout it sits in (checkoutRootOf, which follows
 * no commdir), and the target relative to that checkout's root is compared
 * with the path; a shell command that file-tools-only counts as a write and
 * whose text names the path under any prefix is denied without checkout
 * distinction. Reads and git commands pass: git is a known boundary, found
 * by the morning report's reconciliation (design §3.10).
 *
 * `liftVia: 'board'`: only the rules board's path can lift this rule — the
 * agent must not be able to lift the guard of the record it would write to.
 */
import { dirname, isAbsolute, relative, resolve } from 'node:path'
import { checkoutRootOf, projectOf } from '../data/project-root.ts'
import { shellWriteOf, type Correction, type GuardRule, type RuleVerdict } from './rules.ts'
import { mentionsPath, pathKey } from './mention.ts'

const ALLOW: RuleVerdict = { kind: 'allow' }

/** The exact relative path the rule protects (design §3.5: the file, not the directory). */
const LIFTS_RECORD_PATH = 'docs/guard/lifts.jsonl'

const correctionOf = (path: string): Correction => ({
  fact: `You tried to change the lift record \`${path}\`.`,
  violation: 'That file is the record of the rules the human has lifted, and the harness writes it.',
  rightPath: 'Do not edit this file. Only the human can lift or restore rules. If you think a rule blocks you wrongly, say so in your reply.',
  exception: 'none',
})

/**
 * The rule for one call: `cwd` is the calling session's working directory,
 * against which relative targets resolve and whose project decides whether
 * the checkout the target sits in is this session's at all. Undefined cwd
 * leaves a relative target unresolvable, and an unresolvable target passes.
 */
export function liftFilesOnly(cwd: string | undefined): GuardRule {
  return {
    id: 'lift-files-only',
    detect(call) {
      // File tools: the target, spelled relative or absolute, resolves as the
      // file tools resolve it; the cheap string check keeps every other write
      // free of a disk read (design §3.5 item 1). A `str_replace_editor view`
      // reads, it does not write.
      const args = typeof call.arguments === 'object' && call.arguments !== null && !Array.isArray(call.arguments) ? call.arguments as Record<string, unknown> : undefined
      const viewing = call.name === 'str_replace_editor' && args?.command === 'view'
      const field = call.name === 'str_replace_editor' ? 'path' : 'file_path'
      const spelled = !viewing && typeof args?.[field] === 'string' ? args[field] : undefined
      if (spelled !== undefined) {
        const view = isAbsolute(spelled) ? spelled : cwd === undefined ? undefined : resolve(cwd, spelled)
        if (view !== undefined && pathKey(view).endsWith(`/${LIFTS_RECORD_PATH}`)) {
          if (thisIsTheProjectsRecord(view, cwd)) return { kind: 'deny', rule: 'lift-files-only', correction: correctionOf(spelled) }
        }
        return ALLOW
      }
      // Shell text: only commands file-tools-only counts as writes, through
      // that rule's own detector (design §3.5 item 2).
      const shell = shellWriteOf(call)
      if (shell === undefined) return ALLOW
      return mentionsPath(shell.command, LIFTS_RECORD_PATH)
        ? { kind: 'deny', rule: 'lift-files-only', correction: correctionOf(shell.command) }
        : ALLOW
    },
  }
}

/** Whether the absolute target is `docs/guard/lifts.jsonl` of a checkout of the session's project (design §3.5 item 1). */
function thisIsTheProjectsRecord(target: string, cwd: string | undefined): boolean {
  const root = checkoutRootOf(dirname(target))
  if (root === undefined) {
    // No .git above: outside git, only the session project's own root counts.
    const project = cwd === undefined ? undefined : projectOf(cwd)
    return project !== undefined && pathKey(resolve(project.root, LIFTS_RECORD_PATH)) === pathKey(target)
  }
  if (pathKey(relative(root, target)) !== pathKey(LIFTS_RECORD_PATH)) return false
  // The checkout must belong to the session's project (a work tree's root
  // differs from the main checkout's; projectOf folds both to one project —
  // review finish2 round 2 N27: compare through pathKey, the drive case and
  // slash direction can differ between the .git file and the cwd).
  const sessionProject = cwd === undefined ? undefined : projectOf(cwd)?.root
  if (sessionProject === undefined) return true
  const targetProject = projectOf(root)?.root
  return targetProject !== undefined && pathKey(targetProject) === pathKey(sessionProject)
}
