/**
 * dsh-guard — graph-files-only (docs/ORCHESTRATION.md §2.7, §6.4): the
 * project graph changes only through the graph tools, which keep the
 * history and check revisions, evidence and permissions. File tools that
 * target the graph directory, and shell commands that file-tools-only
 * counts as writes and that name the graph directory, are denied with a
 * four-part correction pointing at those tools. Shell text is taken as
 * file-tools-only takes it (shellCommandOf: `command`, or `text` for
 * terminal_send) and counts as a write only where that quote-aware rule
 * says so. The rule uses the guard framework (rules.ts) but is
 * registered by the glm-hourness/graph row (installGraphFileGuard): only
 * that row knows the graph directory, and only with it enabled does the
 * right path exist. Denials are journaled like the guard row's, with the
 * call's origin (src/guard/origin.ts).
 */
import { isAbsolute, relative, resolve } from 'node:path'
import type { JsonValue } from '../shared/json.ts'
import type { PreExecuteHost, ServiceLookup } from '../shared/dsh-min.ts'
import { GRAPH_FILES_DECLARATION } from '../graph/service.ts'
import { dialectNames, dialectService, dialectWarner, toNativeTool } from '../shared/dialect.ts'
import { sessionRoute } from '../shared/route.ts'
import { baseFor, type ViolationRecord } from './index.ts'
import { originOf } from './origin.ts'
import { evaluate, fileToolsOnly, fileWriteTarget, NATIVE_FACE, renderCorrection, shellCommandOf, type Correction, type GuardRule, type RuleVerdict, type ToolCall } from './rules.ts'

export const GRAPH_FILES_RULE = 'graph-files-only'

const ALLOW: RuleVerdict = { kind: 'allow' }

/** Comparable form of a path: forward slashes, no trailing slash, lower case (Windows file systems ignore case). */
function pathKey(path: string): string {
  return path.replaceAll('\\', '/').replace(/\/+/g, '/').replace(/\/$/, '').toLowerCase()
}

/** After a mention: a path-name character would make it a longer name (docs/graph.svg, docs/graphs). */
const NAME_AFTER = String.raw`[\p{L}\p{N}_.\-]`
/** Before a mention: a path-name character or a separator would make it part of a longer path (x/docs/graph). */
const NAME_BEFORE = String.raw`[\p{L}\p{N}_.\-/:]`

/** Matches a mention of a normalized directory spelling in a normalized command; ./ may precede it. */
function mention(spelling: string): RegExp {
  const escaped = spelling.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return new RegExp(`(?<!${NAME_BEFORE})(?:\\./)?${escaped}(?!${NAME_AFTER})`, 'u')
}

/**
 * The rule for one call: `graphDir` is the absolute graph directory, `cwd`
 * the calling session's working directory, against which relative targets
 * resolve; without it a relative target cannot be judged and passes.
 */
export function graphFilesOnly(graphDir: string, cwd: string | undefined): GuardRule {
  const root = pathKey(resolve(graphDir))
  const inside = (target: string): boolean => {
    if (!isAbsolute(target) && cwd === undefined) return false
    const key = pathKey(cwd === undefined ? resolve(target) : resolve(cwd, target))
    return key === root || key.startsWith(`${root}/`)
  }
  const fromCwd = cwd === undefined ? undefined : pathKey(relative(resolve(cwd), resolve(graphDir)))
  const mentions = [root, ...(fromCwd === undefined || fromCwd.length === 0 || fromCwd.startsWith('..') || isAbsolute(fromCwd) ? [] : [fromCwd])].map(mention)
  const deny = (fact: string): RuleVerdict => ({ kind: 'deny', rule: GRAPH_FILES_RULE, correction: correction(fact, resolve(graphDir)) })
  return {
    id: GRAPH_FILES_RULE,
    declare: GRAPH_FILES_DECLARATION,
    detect(call) {
      const target = fileWriteTarget(call)
      if (target !== undefined) return inside(target) ? deny(`You tried to write "${target}".`) : ALLOW
      // The shell text as file-tools-only reads it (terminal_send carries it in `text`).
      const shell = shellCommandOf(call)
      if (shell === undefined || fileToolsOnly.detect(call, NATIVE_FACE).kind !== 'deny') return ALLOW
      const normalized = pathKey(shell.command)
      return mentions.some(pattern => pattern.test(normalized)) ? deny(`You tried to change project graph files through the shell: "${shell.command}".`) : ALLOW
    },
  }
}

function correction(fact: string, graphDir: string): Correction {
  return {
    fact,
    violation: `That is inside the project graph (${graphDir}); graph files change only through the graph tools, which keep the history and check revisions, evidence and permissions.`,
    rightPath: 'Read the node with graph_show or graph_open, then change it with graph_propose, graph_status, graph_edit, graph_link, graph_unlink, graph_comment, graph_verify or graph_decide. A rendered picture such as graph.svg is regenerated by the renderer, not edited.',
    exception: 'Approving, rejecting and deciding need the human: they do it in the project graph panel, or they tell you in the chat and you send their words as relay. If a node file is broken or a change has no tool, tell the human: they fix node files by hand or restore them with git.',
  }
}

/**
 * Install the rule on `tools/pre-execute`, outermost so that a shell write
 * into the graph gets this correction instead of file-tools-only's.
 * `graphDirFor` maps the calling session's working directory to the graph
 * directory, or undefined when there is none to protect. Every denial goes
 * to `journal` in the guard's record shape (the violation journal,
 * CHARTER.md §7.1 clause 11); the journal never rejects into the call.
 * Nested transport calls pass, as in the guard row.
 */
export function installGraphFileGuard(ctx: PreExecuteHost & ServiceLookup, graphDirFor: (cwd: string | undefined) => string | undefined, journal: (record: ViolationRecord) => void): () => void {
  const warn = dialectWarner('graph')
  return ctx.on('tools/pre-execute', async (payload, next) => {
    if (payload.parent !== undefined) return next()
    const header = payload.agent?.session?.header.cwd
    const cwd = typeof header === 'string' && header.length > 0 ? header : undefined
    const dir = graphDirFor(cwd)
    if (dir === undefined) return next()
    // Every route, like the guard row (ORCHESTRATION.md §6.2). Relative targets
    // resolve as the file tools resolve them; the rule judges the DSH native the
    // call runs (a GLM Write is a write).
    const dialect = dialectService(ctx, warn)
    const call: ToolCall = { name: toNativeTool(dialect, payload.name, warn), arguments: (payload.arguments ?? {}) as JsonValue }
    const verdict = evaluate([graphFilesOnly(dir, baseFor(ctx, payload.agent) ?? cwd)], call)
    if (verdict.kind !== 'deny') return next()
    const reason = renderCorrection(verdict.correction)
    const route = sessionRoute(payload.agent?.session)
    const origin = originOf(dialectNames(dialect, payload.agent, route, warn) !== undefined, route)
    journal({ at: new Date().toISOString(), rule: verdict.rule, tool: payload.name, agentId: payload.agent?.id, sessionId: payload.agent?.session?.id, ...origin, correction: reason })
    return { kind: 'deny', reason }
  }, { prepend: true })
}
